const PORT = 9222;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const res = await fetch(`http://127.0.0.1:${PORT}/json/new?${encodeURIComponent("http://localhost:5173/")}`, { method: "PUT" });
const target = await res.json();
const ws = new WebSocket(target.webSocketDebuggerUrl);
const pending = new Map();
let nextId = 0;
const send = (method, params = {}) => new Promise((resolve) => { const id = ++nextId; pending.set(id, resolve); ws.send(JSON.stringify({ id, method, params })); });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id) { pending.get(m.id)?.(m); pending.delete(m.id); } };
await new Promise((r) => (ws.onopen = r));
await send("Runtime.enable");
await sleep(3500);
const evaluate = async (expression) => (await send("Runtime.evaluate", { expression, returnByValue: true, awaitPromise: true })).result?.result?.value;
console.log("frames after load:", await evaluate("window.__survivexFrames ?? 'undefined'"));
console.log("last delta:", await evaluate("window.__survivexDelta ?? 'undefined'"));
await sleep(1000);
console.log("frames 1s later:", await evaluate("window.__survivexFrames ?? 'undefined'"));
console.log("last delta:", await evaluate("window.__survivexDelta ?? 'undefined'"));
console.log("canvas count:", await evaluate("document.querySelectorAll('canvas').length"));
ws.close();
